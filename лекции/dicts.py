#Методы словарей:
#.keys() - возвращает ключи в формате dict_keys, они не копируют словарь а просто <<смотрят>> на словарь
my_dict = {"a": 2, "b": 3, "c": 4}
print('my_dict = {"a": 2, "b": 3, "c": 4}, type:', type(my_dict.keys()))
print(my_dict.keys())
#.values() - возвращает значения в формате dict_values, они не копируют словарь а просто <<смотрят>> на словарь
my_dict = {"a": 2, "b": 3, "c": 4}
print('my_dict = {"a": 2, "b": 3, "c": 4}, type:', type(my_dict.values()))
print(my_dict.values())
#.items() - возвращает значения в формате dict_items, они не копируют словарь а просто <<смотрят>> на словарь
my_dict = {"a": 2, "b": 3, "c": 4}
print('my_dict = {"a": 2, "b": 3, "c": 4}, type:', type(my_dict.items()))
print(my_dict.items())


#setdefault(key, value) - Если значения нет, то добавляется в словарь и возвращаем значение, а если уже есть,
# то словарь не меняется
my_dict = {"a": 2, "b": 3, "c": 4}
new_numb = my_dict.setdefault("a", 5)
print(new_numb)
