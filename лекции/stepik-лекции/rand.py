import random
#Чтобы подключить модуль воспользуемся import random
#Основные функции:
#1)random.randint([x1;x2]) - генерирует одно любое число от х1 до х2 включительно
#2)random.randrange([x1;x2)) - генерирует одно любое число от х1 включительно до х2 невключительно
#3)random.random() - генирурет float число в диапазоне от [0.0;1.0)
#4)random.uniform([x1;x2]) - тоже самое что и random, но можем указать диапазон от х1 до х2 включительно
#5)random.shuffle()  -принимает список в качестве обязательного аргумента и перемешивает его случайным образом.
#6)random.choice() - принимает список в качестве обязательного аргумента и возвращает один случайный элемент.
#7)random.sample() - принимает два обязательных аргумента: первый – коллекция (последовательность),
# которая поддерживает индексацию (список, строка, кортеж), второй – количество случайных элементов.
# Возвращает список из указанного количества уникальных (имеющих разные индексы) случайных элементов.

#Можем указать начальное число с помощью random.seed(numb), тогда число всегда будет одно
print(random.randint(1, 100))
random.seed(50)
print(random.randint(1, 100))
#Алгоритм лежащий в основное модуля random называетс вихрь Мерсенна
